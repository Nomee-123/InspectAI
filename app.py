def render_results(analysis: dict[str, Any]) -> None:
    alignment = analysis["alignment"]
    measurements = analysis["measurements"]
    dimensions = analysis["dimensions"]
    reference_dimensions = dimensions["reference"]
    width, height = int(reference_dimensions[0]), int(reference_dimensions[1])
    aspect = width / max(1, height)

    components.kicker("result summary")
    components.chips(
        [
            (status_label(alignment["status"]), status_tone(alignment["status"])),
            (f"method · {alignment['method']}", ""),
            (f"confidence · {alignment['confidence']}", ""),
            (f"changed · {as_number(measurements['final_changed'], 2, '%')}", ""),
            (f"regions · {analysis['region_count']}", "amber" if analysis["region_count"] else ""),
            (
                "photometric applied" if measurements["photometric_applied"] else "photometric not applied",
                "amber" if measurements["photometric_applied"] else "",
            ),
        ]
    )
    components.render_gauges(analysis["gauges"], reduced=reduced)

    register_tab, analyze_tab, verify_tab = st.tabs(["REGISTER", "ANALYZE", "VERIFY"])

    with register_tab:
        st.markdown(
            '<div class="vc-note">Every marker, matrix, status and residual below belongs to a real '
            "step returned by <code>inspect_images</code>. LOCKED / AMBIGUOUS / REJECTED copy the "
            "step status; the ghost candidate is the other real ambiguous step. Scrub or press Play "
            "to replay the transform.</div>",
            unsafe_allow_html=True,
        )
        components.render_register(analysis["register"], reduced=reduced)
        components.readouts(
            [
                ("rotation", as_number(alignment["rotation"], 2, "°")),
                ("scale", as_number(alignment["scale"], 5)),
                ("shift", f"{alignment['shift'][0]:.2f}, {alignment['shift'][1]:.2f} px"),
                ("overlap", as_number(alignment["overlap"] * 100.0, 1, "%")),
            ]
        )
        st.caption(f"Final matrix (canvas → source, OpenCV WARP_INVERSE_MAP): {matrix_text(alignment['final_matrix'])}")
        orientation_steps = [
            step for step in analysis["steps"] if step["model"] == "orientation"
        ]
        if orientation_steps:
            st.caption(
                "Orientation is a visible step: "
                + " · ".join(
                    f"{step['name']} → {step['status']}" for step in orientation_steps
                )
            )

    with analyze_tab:
        components.readouts(
            [
                ("surviving regions", str(analysis["region_count"])),
                ("detected components", str(analysis["detected_region_count"])),
                ("filtered components", str(analysis["filtered_region_count"])),
                ("minimum region area", f"{analysis['minimum_region_area']} px"),
            ]
        )
        left, right = st.columns(2)
        with left:
            components.image_panel(
                "reference",
                analysis["reference_uri"],
                meta=f"{width} × {height} px",
                caption="Reference canvas used for every comparison.",
                aspect=aspect,
            )
            components.image_panel(
                "difference heatmap",
                analysis["heatmap_uri"],
                meta=f"ΔE threshold {as_number(measurements['threshold'], 2)}",
                caption=(
                    "Turbo colormap of the Lab ΔE magnitude after alignment"
                    + (
                        ", with photometric normalization applied before comparison"
                        if measurements["photometric_applied"]
                        else ""
                    )
                    + ". Scaled for display, not a defect score."
                ),
                aspect=aspect,
            )
        with right:
            components.image_panel(
                "aligned test",
                analysis["aligned_uri"],
                meta=f"{alignment['method']} alignment",
                caption="Test image after the accepted transform, shown on the reference canvas.",
                aspect=aspect,
            )
            components.image_panel(
                "change mask",
                analysis["mask_uri"],
                meta=f"{analysis['region_count']} regions",
                caption="Pixels over the adaptive Lab threshold, after 3×3 open/close cleanup.",
                aspect=aspect,
            )
        components.kicker("change regions")
        components.render_regions(
            image_uri=analysis["aligned_uri"],
            regions=analysis["regions"],
            width=width,
            height=height,
            minimum_area=analysis["minimum_region_area"],
            reduced=reduced,
        )
        components.kicker("reference / aligned wipe")
        components.render_swipe(
            title="reference vs aligned test",
            meta=f"{alignment['method']} · {alignment['status']}",
            top_uri=analysis["reference_uri"],
            bottom_uri=analysis["aligned_uri"],
            width=width,
            height=height,
            reduced=reduced,
        )

    with verify_tab:
        lab_state = method_state(measurements["pixel_change_indicated"])
        canny_state = method_state(measurements["edge_change_indicated"])
        ssim_state = method_state(measurements["ssim_change_indicated"])
        if measurements["method_disagreement"]:
            st.warning(
                "The independent methods disagree in direction: "
                f"Lab ΔE {lab_state}; Canny edges {canny_state}; SSIM {ssim_state}. "
                "No single method is presented as a confirmed result. Inspect the heatmap, "
                "edges and regions directly."
            )
        else:
            st.info(
                f"Method indications: Lab ΔE {lab_state}; Canny edges {canny_state}; "
                f"SSIM {ssim_state}. Agreement between heuristics is not calibration and "
                "does not confirm a real-world change."
            )
        components.readouts(
            [
                ("edge similarity", as_number(measurements["edge_similarity"], 2, "%")),
                ("edge disagreement", as_number(measurements["edge_disagreement"], 2, "%")),
                ("SSIM", as_number(measurements["ssim"], 4)),
                ("pixel change gate", "passed" if measurements["pixel_change_indicated"] else "not passed"),
            ]
        )
        components.readouts(
            [
                ("Lab ΔE indication", lab_state),
                ("Canny indication", canny_state),
                ("SSIM indication", ssim_state),
                ("initial changed", as_number(measurements["initial_changed"], 2, "%")),
            ]
        )
        components.readouts(
            [
                ("final changed", as_number(measurements["final_changed"], 2, "%")),
                ("valid pixels", f"{measurements['valid_pixels']:,}"),
                ("photometric improvement", as_number(measurements["photometric_improvement"], 4)),
                ("photometric state", "applied" if measurements["photometric_applied"] else "not applied"),
            ]
        )
        if measurements["photometric_reason"]:
            components.note(f"Photometric normalization: {measurements['photometric_reason']}")

        components.kicker("agent feed")
        components.render_feed(analysis["agent_trace"])

        with st.expander("Evidence lines", expanded=False):
            for line in analysis["evidence"]:
                st.markdown(f"- {line}")

        with st.expander("Agent decisions", expanded=False):
            if analysis["decisions"]:
                for decision in analysis["decisions"]:
                    st.markdown(f"- {decision}")
            else:
                st.markdown("- No explicit agent decisions were recorded for this pair.")

        with st.expander("Uncertainty warnings", expanded=True):
            if analysis["warnings"]:
                for warning in analysis["warnings"]:
                    st.markdown(f"- {warning}")
            else:
                st.markdown("- No additional uncertainty warnings were recorded for this pair.")

        with st.expander("Limitations", expanded=False):
            for limitation in analysis["limitations"]:
                st.markdown(f"- {limitation}")

        with st.expander("Function trace", expanded=False):
            st.json(analysis["function_trace"])

        components.kicker("json report")
        st.caption(
            "Schema v2. Contains measurements, thresholds, alignment steps and keypoints. "
            "Contains no image pixels, previews or data URIs."
        )
        components.report_preview(analysis["report_json"])
        st.download_button(
            "⤓ Download JSON report",
            data=analysis["report_json"].encode("utf-8"),
            file_name="inspectai_report.json",
            mime="application/json",
            use_container_width=True,
        )


