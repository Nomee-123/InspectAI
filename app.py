def as_number(value: Any, digits: int = 2, suffix: str = "") -> str:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return "not scored"
    if not np.isfinite(number):
        return "not scored"
    return f"{number:.{digits}f}{suffix}"


def matrix_text(matrix: Any) -> str:
    values = np.asarray(matrix, dtype=float)
    if values.shape != (3, 3):
        return "not available"
    rows = []
    for row in values[:2]:
        rows.append("  ".join(f"{number: .5f}" for number in row))
    return " / ".join(rows)


def aspect_text(width: int, height: int) -> str:
    ratio = Fraction(int(width), int(height))
    return f"{ratio.numerator}:{ratio.denominator} · {width / height:.3f}"


def status_label(status: str) -> str:
    return {
        "applied": "ALIGNMENT LOCKED",
        "ambiguous": "ALIGNMENT AMBIGUOUS",
        "rejected": "ALIGNMENT REJECTED",
        "not_needed": "ALIGNMENT NOT NEEDED",
    }.get(status, status.replace("_", " ").upper())


def status_tone(status: str) -> str:
    return {"applied": "ok", "ambiguous": "amber", "rejected": "red"}.get(status, "")


def method_state(value: Any) -> str:
    """Describe a real method indication without turning it into a verdict."""
    if value is None:
        return "not scored"
    return "indicates change" if bool(value) else "no change indicated"


def signature_for(source: str, reference_bytes: bytes, test_bytes: bytes) -> str:
    digest = hashlib.sha256()
    digest.update(source.encode("utf-8"))
    digest.update(len(reference_bytes).to_bytes(8, "big"))
    digest.update(reference_bytes)
    digest.update(len(test_bytes).to_bytes(8, "big"))
    digest.update(test_bytes)
    return digest.hexdigest()


